col1, col2 = st.columns([2, 3])
with col1:
    query = st.text_input("용어 검색", placeholder="예: PAM, 시퀀싱, 오프타깃").strip().lower()
with col2:
    category = st.radio("분류", ["전체"] + CATEGORIES, horizontal=True)

shown = [
    (term, cat, desc) for term, cat, desc in TERMS
    if (category == "전체" or cat == category)
    and (not query or query in term.lower() or query in desc.lower())
]

st.markdown("---")
st.write(f"{len(shown)}개의 용어")

if not shown:
    st.info("검색 결과가 없어요. 다른 단어로 찾아보거나 분류를 '전체'로 바꿔 보세요.")

for term, cat, desc in shown:
    with st.container(border=True):
        st.markdown(f"**{term}**")
        st.caption(cat)
        st.write(desc)
